"""Presentation-only layout for the downloader's existing controls."""
import os

from PyQt6.QtCore import QSize, Qt
from PyQt6.QtWidgets import (QCheckBox, QHBoxLayout, QLabel, QLineEdit,
                            QProgressBar, QPushButton, QSizePolicy, QTextEdit, QVBoxLayout)

from ui_theme import STYLESHEET, GlassComboBox, ToggleCheckBox, card, glow, line_icon, ui_font


def label(text, name=None):
    widget = QLabel(text)
    widget.setTextFormat(Qt.TextFormat.PlainText)
    if name:
        widget.setObjectName(name)
    return widget


def icon_label(kind, size=24):
    widget = label('')
    widget.setPixmap(line_icon(kind, size=size).pixmap(size, size))
    widget.setFixedSize(size, size)
    return widget


def button(text, kind, callback, name=None):
    widget = QPushButton(text)
    widget.setIcon(line_icon(kind))
    widget.setIconSize(QSize(20, 20))
    widget.setCursor(Qt.CursorShape.PointingHandCursor)
    widget.clicked.connect(callback)
    if name:
        widget.setObjectName(name)
    return widget


def panel():
    widget = card()
    layout = QVBoxLayout(widget)
    layout.setContentsMargins(18, 16, 18, 16)
    layout.setSpacing(12)
    return widget, layout


def build_interface(self):
    self.setFont(ui_font())
    self.setStyleSheet(STYLESHEET)
    layout = QVBoxLayout(self)
    layout.setContentsMargins(24, 22, 24, 24)
    layout.setSpacing(18)

    header = QHBoxLayout()
    header.setSpacing(13)
    header.addWidget(icon_label('youtube', 42))
    title = QVBoxLayout()
    title.setSpacing(3)
    title.addWidget(label('YouTube 下载工具', 'AppTitle'))
    title.addWidget(label('视频、音频与播放列表，轻松保存到本地', 'Subtitle'))
    header.addLayout(title)
    header.addStretch()

    version_card, version_layout = panel()
    version_layout.setContentsMargins(14, 12, 14, 12)
    versions = QHBoxLayout()
    text = QVBoxLayout()
    text.setSpacing(5)
    current = QHBoxLayout()
    current.addWidget(label('yt-dlp', 'Muted'))
    self.lbl_current = label(self.current_version, 'SectionTitle')
    current.addWidget(self.lbl_current)
    text.addLayout(current)
    latest = QHBoxLayout()
    latest.addWidget(label('最新稳定版', 'Muted'))
    self.lbl_latest = label(self.latest_version)
    self.lbl_latest.setCursor(Qt.CursorShape.PointingHandCursor)
    self.lbl_latest.mousePressEvent = self.open_latest_release
    latest.addWidget(self.lbl_latest)
    text.addLayout(latest)
    versions.addLayout(text)
    versions.addSpacing(10)
    self.btn_update = button('安装 / 更新', 'cloud', self.update_engine, 'UpdateButton')
    self.btn_update.setToolTip('独立安装或更新 yt-dlp，无需重新编译软件')
    self.btn_update.setMinimumHeight(48)
    versions.addWidget(self.btn_update)
    version_layout.addLayout(versions)
    header.addWidget(version_card)
    layout.addLayout(header)

    body = QHBoxLayout()
    body.setSpacing(18)
    left, right = QVBoxLayout(), QVBoxLayout()
    left.setSpacing(14)
    right.setSpacing(14)
    body.addLayout(left, 46)
    body.addLayout(right, 54)
    layout.addLayout(body, 1)

    path_card, path_layout = panel()
    row = QHBoxLayout()
    row.addWidget(icon_label('folder', 32))
    texts = QVBoxLayout()
    texts.setSpacing(3)
    texts.addWidget(label('保存到', 'Muted'))
    self.lbl_path = label(self.download_path, 'PathValue')
    self.lbl_path.setToolTip(self.download_path)
    self.lbl_path.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    texts.addWidget(self.lbl_path)
    row.addLayout(texts, 1)
    path_layout.addLayout(row)
    row = QHBoxLayout()
    self.btn_choose = button('更改文件夹', 'folder', self.choose_path)
    self.btn_open = button('打开文件夹', 'open', self.open_folder)
    row.addWidget(self.btn_choose)
    row.addWidget(self.btn_open)
    path_layout.addLayout(row)
    left.addWidget(path_card)

    proxy_card, proxy_layout = panel()
    row = QHBoxLayout()
    self.cb_proxy = ToggleCheckBox('使用代理')
    self.cb_proxy.setChecked(self.connection.use_proxy)
    self.cb_proxy.setToolTip('用于视频下载；yt-dlp 引擎安装和更新使用系统网络配置。')
    row.addWidget(self.cb_proxy)
    row.addStretch()
    self.proxy_type_combo = GlassComboBox()
    self.proxy_type_combo.addItems(['http', 'socks5', 'socks4'])
    self.proxy_type_combo.setCurrentText(self.connection.proxy_type)
    self.proxy_type_combo.setMinimumWidth(110)
    self.proxy_type_combo.setAccessibleName('代理类型')
    row.addWidget(self.proxy_type_combo)
    proxy_layout.addLayout(row)
    row = QHBoxLayout()
    host, port = QVBoxLayout(), QVBoxLayout()
    host.setSpacing(6)
    port.setSpacing(6)
    host.addWidget(label('IP / 主机', 'Muted'))
    self.proxy_ip_edit = QLineEdit(self.connection.proxy_ip)
    self.proxy_ip_edit.setPlaceholderText('127.0.0.1')
    self.proxy_ip_edit.setAccessibleName('代理 IP 或主机名')
    host.addWidget(self.proxy_ip_edit)
    port.addWidget(label('端口', 'Muted'))
    self.proxy_port_edit = QLineEdit(self.connection.proxy_port)
    self.proxy_port_edit.setMaximumWidth(90)
    self.proxy_port_edit.setAccessibleName('代理端口')
    port.addWidget(self.proxy_port_edit)
    row.addLayout(host, 1)
    row.addLayout(port)
    self.btn_proxy_confirm = button('确认', 'check', self.save_proxy_settings)
    row.addWidget(self.btn_proxy_confirm, 0, Qt.AlignmentFlag.AlignBottom)
    proxy_layout.addLayout(row)
    self.cb_proxy.toggled.connect(self.on_proxy_check_changed)
    left.addWidget(proxy_card)

    cookie_card, cookie_layout = panel()
    self.cb_cookie = ToggleCheckBox('使用 Cookie 登录下载')
    self.cb_cookie.setToolTip('IG 视频请先导入有效的 IG Cookie；其他需登录的内容使用对应站点 Cookie。支持 Netscape 文本或浏览器 Cookie JSON；新设置用于下一批下载。')
    self.cb_cookie.setChecked(self.connection.use_cookie)
    self.cb_cookie.toggled.connect(self.save_connection_preferences)
    cookie_layout.addWidget(self.cb_cookie)
    row = QHBoxLayout()
    self.btn_import_cookie = button('导入 Cookie 文件', 'file', self.import_cookie)
    row.addWidget(self.btn_import_cookie)
    self.lbl_cookie_file = label('已加载：' + os.path.basename(self.cookie_file)
                                 if self.cookie_file else '未加载 Cookie', 'Muted')
    self.lbl_cookie_file.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    row.addWidget(self.lbl_cookie_file, 1)
    cookie_layout.addLayout(row)
    left.addWidget(cookie_card)
    self.on_proxy_check_changed()

    progress_card, progress_layout = panel()
    row = QHBoxLayout()
    row.addWidget(icon_label('gauge', 28))
    self.lbl_status = label('就绪', 'StatusValue')
    row.addWidget(self.lbl_status, 1)
    self.lbl_percent = label('0%', 'SectionTitle')
    row.addWidget(self.lbl_percent)
    progress_layout.addLayout(row)
    self.download_progress = QProgressBar()
    self.download_progress.setRange(0, 100)
    self.download_progress.setValue(0)
    self.download_progress.setTextVisible(False)
    self.download_progress.setFixedHeight(14)
    self.download_progress.setAccessibleName('当前文件下载进度')
    progress_layout.addWidget(self.download_progress)
    row = QHBoxLayout()
    self.lbl_progress = label('进度： - / -', 'Muted')
    self.lbl_speed = label('速度：—', 'Muted')
    row.addWidget(self.lbl_progress)
    row.addStretch()
    row.addWidget(self.lbl_speed)
    progress_layout.addLayout(row)
    self.lbl_file = label('当前文件： -', 'Muted')
    self.lbl_file.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    progress_layout.addWidget(self.lbl_file)
    progress_layout.addStretch()
    hint = label('下载过程中可随时暂停，稍后继续。', 'Subtitle')
    hint.setWordWrap(True)
    progress_layout.addWidget(hint)
    left.addWidget(progress_card, 1)

    input_card, input_layout = panel()
    row = QHBoxLayout()
    row.addWidget(icon_label('link', 30))
    row.addWidget(label('添加下载链接', 'SectionTitle'))
    row.addStretch()
    row.addWidget(label('一行一个链接', 'Muted'))
    input_layout.addLayout(row)
    self.edit_url = QTextEdit()
    self.edit_url.setAcceptRichText(False)
    self.edit_url.setTabChangesFocus(True)
    self.edit_url.setAccessibleName('下载链接，每行一个')
    self.edit_url.setPlaceholderText('粘贴 YouTube、Instagram（IG）或 Facebook（FB）视频链接\n\n支持一次添加多个链接，每行一个。')
    self.edit_url.setMinimumHeight(110)
    self.edit_url.setMaximumHeight(150)
    input_layout.addWidget(self.edit_url)
    site_hint = label('Instagram（IG）：先导入有效的 IG Cookie，再粘贴视频链接。\n'
                      'Facebook（FB）：公开视频可直接下载；需登录的内容请导入对应 Cookie。', 'SiteHint')
    site_hint.setWordWrap(True)
    input_layout.addWidget(site_hint)
    row = QHBoxLayout()
    row.addWidget(icon_label('tune', 18))
    row.addWidget(label('下载质量', 'Muted'))
    row.addStretch()
    input_layout.addLayout(row)
    self.combo_quality = GlassComboBox()
    self.combo_quality.setAccessibleName('下载质量')
    self.combo_quality.addItems(['最高质量（推荐）', '1080p（或更低）', '720p（或更低）',
                                 '480p（或更低）', '最小体积（适合流量少）', '仅音频（MP3 192kbps）'])
    input_layout.addWidget(self.combo_quality)
    self.cb_playlist = QCheckBox('下载整个播放列表 / 频道（如果链接包含）')
    input_layout.addWidget(self.cb_playlist)
    right.addWidget(input_card)

    actions = QHBoxLayout()
    actions.setSpacing(14)
    self.btn_main = button('开始下载', 'download', self.toggle_main, 'PrimaryButton')
    self.btn_cancel = button('取消全部', 'close', self.cancel_all, 'CancelButton')
    self.btn_cancel.setEnabled(False)
    for widget in (self.btn_main, self.btn_cancel):
        widget.setFixedHeight(58)
        widget.setIconSize(QSize(25, 25))
        actions.addWidget(widget, 1)
    glow(self.btn_main, '#4032d7b1')
    right.addLayout(actions)

    log_card, log_layout = panel()
    row = QHBoxLayout()
    row.addWidget(icon_label('file', 25))
    row.addWidget(label('下载日志', 'SectionTitle'))
    row.addStretch()
    row.addWidget(label('保留最近 2000 行', 'Subtitle'))
    log_layout.addLayout(row)
    self.log_area = QTextEdit()
    self.log_area.setObjectName('LogArea')
    self.log_area.setAccessibleName('下载日志')
    self.log_area.setReadOnly(True)
    self.log_area.setPlaceholderText('下载与更新记录将在这里显示…')
    self.log_area.document().setMaximumBlockCount(2000)
    self.log_area.setMinimumHeight(100)
    log_layout.addWidget(self.log_area, 1)
    right.addWidget(log_card, 1)

    # Follow the visible columns rather than Qt's creation order when using Tab.
    controls = [self.btn_update, self.btn_choose, self.btn_open, self.cb_proxy,
                self.proxy_type_combo, self.proxy_ip_edit, self.proxy_port_edit,
                self.btn_proxy_confirm, self.cb_cookie, self.btn_import_cookie,
                self.edit_url, self.combo_quality, self.cb_playlist, self.btn_main,
                self.btn_cancel, self.log_area]
    for first, second in zip(controls, controls[1:]):
        self.setTabOrder(first, second)
